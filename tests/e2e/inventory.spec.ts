import { test, expect, readPantry } from './fixtures'

test('inventory quantities persist and restock exactly; deleting requires confirmation', async ({ page }) => {
  await page.goto('#inventory')
  await page.getByRole('button', { name: '添加食物', exact: true }).click()
  await page.getByLabel('食物名称', { exact: true }).fill('饺子')
  await page.getByLabel('剩余数量', { exact: true }).fill('0.5')
  await page.getByLabel('补货提醒线（选填）', { exact: true }).fill('1')
  await page.getByRole('button', { name: '保存食物', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  const card = page.getByLabel('食物：饺子', { exact: true })
  await expect(card).toContainText('该补货了')
  await card.getByRole('button', { name: '补货', exact: true }).click()
  await page.getByLabel('补货数量（份）', { exact: true }).fill('0.25')
  await page.getByRole('button', { name: '确认补货', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.reload()
  await expect(card).toContainText('0.75')
  expect((await readPantry(page)).foods[0].lowStockAt).toBe(1)
  await page.getByRole('button', { name: '删除饺子', exact: true }).click()
  await page.getByRole('button', { name: '保留食物', exact: true }).click()
  await expect(card).toBeVisible()
  await page.getByRole('button', { name: '删除饺子', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(card).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('heading', { name: '从第一样食物开始', exact: true })).toBeVisible()
})
